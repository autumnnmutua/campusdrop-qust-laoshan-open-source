/** Characters pairs of a text (Chinese has no spaces): the unit for the assistant's keyword retrieval. */
export function bigrams(text: string): Set<string> {
  const clean = text.toLowerCase().replace(/[\s，。？！、；：“”‘’（）()?!.,:;"'\-—·]/g, '');
  const out = new Set<string>();
  for (let i = 0; i < clean.length - 1; i++) out.add(clean.slice(i, i + 2));
  if (clean.length === 1) out.add(clean);
  return out;
}
/** How rare each character pair is across the FAQ: common pairs like 配送 or 订单 count for little. */
let idf: Map<string, number> | null = null;
function weights(): Map<string, number> {
  if (idf) return idf;
  const df = new Map<string, number>();
  for (const [, q, a] of FAQ) for (const g of new Set([...bigrams(q), ...bigrams(a)])) df.set(g, (df.get(g) ?? 0) + 1);
  idf = new Map([...df].map(([g, n]) => [g, Math.log((FAQ.length + 1) / (n + 0.5))]));
  return idf;
}
/** FAQ entries ranked by overlap with a question, rare pairs weighted up (questions count double). */
export function searchFaq(question: string, limit = 4): { topic: string; question: string; answer: string; score: number }[] {
  const q = bigrams(question), w = weights();
  if (!q.size) return [];
  return FAQ.map(([topic, faqQ, answer]) => {
    const a = bigrams(faqQ), b = bigrams(answer);
    let score = 0;
    for (const g of q) { const k = w.get(g) ?? 0; if (a.has(g)) score += 2 * k; if (b.has(g)) score += k; }
    return { topic, question: faqQ, answer, score: score / Math.sqrt(q.size) };
  }).filter(r => r.score > 0).sort((x, y) => y.score - x.score).slice(0, limit);
}
