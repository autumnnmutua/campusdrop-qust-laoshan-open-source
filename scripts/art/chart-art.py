"""Generates the stylised Laoshan "chart" (contour lines on land, isobaths at sea) used by the home hero and the intro.

Not a survey: the relief is invented so that the shapes read as "mountains by the sea", with Laoshan to the north-east and
the sea to the south-east like the real coast. Run once: python3 scripts/art/chart-art.py > src/client/chart-art-data.ts
Needs numpy and scikit-image (dev only; the site never runs this).
"""
import json, math, sys
import numpy as np
from skimage import measure

W, H, STEP = 1600, 900, 4
rng = np.random.default_rng(27)
ys, xs = np.mgrid[0:H:STEP, 0:W:STEP].astype(float)

def fbm(octaves=5, scale=520.0):
    out = np.zeros_like(xs)
    amp, freq = 1.0, 1.0 / scale
    for _ in range(octaves):
        phase = rng.uniform(0, 1000, 4)
        out += amp * (np.sin(xs * freq + phase[0]) * np.cos(ys * freq * 1.3 + phase[1])
                      + np.sin((xs + ys) * freq * 0.7 + phase[2]) * 0.5)
        amp *= 0.5; freq *= 2.03
    return out

# Coast: a bay sweeping from the bottom middle up to the right edge (sea in the south-east), with headlands.
coast_noise = fbm(4, 260.0)
coast_y = 600 - 210 * np.tanh((xs - 1160) / 300) + 46 * coast_noise[:, :] * 0 + 0
coast_y = coast_y + 38 * np.sin(xs / 140.0 + 1.3) + 22 * np.sin(xs / 61.0) + 30 * fbm(3, 180.0)
signed = ys - coast_y  # > 0 at sea
noise = fbm()
fine = fbm(5, 150.0)

# Land: Laoshan's summits to the north-east, a quiet plain to the west where the headline sits.
peaks = [(1300, 120, 200, 1.0), (1500, 230, 150, .82), (1120, 260, 150, .66), (1400, 380, 110, .5), (980, 150, 130, .4), (1560, 60, 120, .7)]
mount = np.zeros_like(xs)
for px, py, r, hgt in peaks:
    mount += hgt * np.exp(-(((xs - px) ** 2) / (2 * r * r) + ((ys - py) ** 2) / (2 * (r * .85) ** 2)))
mask = np.clip(mount * 1.6, 0, 1)
land = mount * 15 + (np.abs(fine) * -2.2 + fine * 1.2) * mask * 2.2 + noise * 0.6 + np.clip(-signed, 0, 240) / 240.0
land[signed > 0] = -1

# Sea: depth grows away from the shore; two small islands off the coast.
islands = [(1300, 760, 46, 1.0), (1500, 640, 30, .8)]
isl = np.zeros_like(xs)
for px, py, r, hgt in islands:
    isl += hgt * np.exp(-(((xs - px) ** 2) + ((ys - py) ** 2) * 1.6) / (2 * r * r))
sea = np.clip(signed, 0, None) / 30.0 + noise * 0.9 + fine * .5 - isl * 9
sea[signed <= 0] = -1

def chaikin(pts, n=2):
    for _ in range(n):
        if len(pts) < 3: break
        q = pts[:-1] * .75 + pts[1:] * .25; r = pts[:-1] * .25 + pts[1:] * .75
        out = np.empty((len(q) * 2, 2)); out[0::2] = q; out[1::2] = r
        pts = np.vstack([pts[:1], out, pts[-1:]])
    return pts

def paths(field, levels, min_len):
    res = []
    for lv in levels:
        for c in measure.find_contours(field, lv):
            pts = c[:, ::-1] * STEP
            pts = measure.approximate_polygon(pts, 2.2)
            if len(pts) < 4: continue
            length = np.sum(np.hypot(*np.diff(pts, axis=0).T))
            if length < min_len: continue
            pts = chaikin(pts)
            d = 'M' + ' '.join(f'{x:.0f} {y:.0f}' for x, y in pts)
            res.append({'d': d, 'level': round(float(lv), 2), 'len': int(length)})
    return res

contours = paths(land, np.concatenate([[0.35, 0.7], np.arange(1.2, float(land.max()), 1.1)]), 110)
isobaths = paths(sea, np.arange(1.2, float(sea.max()), 1.8), 60)

coast = paths(-signed, [0.0], 400)
# Campus (fix) and station on the plain near the foot of the ridge; the route bends along the road between them.
campus, station = (905, 505), (762, 612)
route = 'M762 612 C790 600 806 572 836 560 S884 530 905 505'
out = {'w': W, 'h': H, 'contours': contours, 'isobaths': isobaths, 'coast': max(coast, key=lambda c: c['len'])['d'] if coast else '', 'campus': campus, 'station': station, 'route': route}
sys.stderr.write(f"contours {len(contours)} isobaths {len(isobaths)} bytes {len(json.dumps(out))}\n")
print('/* Generated by scripts/art/chart-art.py: a stylised chart of the Laoshan coast (invented relief, not survey data). */')
print('export interface ChartLine { d: string; level: number; len: number }')
print('export const CHART: { w: number; h: number; contours: ChartLine[]; isobaths: ChartLine[]; coast: string; campus: [number, number]; station: [number, number]; route: string } = ' + json.dumps(out, separators=(',', ':')) + ';')
